import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, unlinkSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const localeRoot = join(root, 'app', '[locale]');
const englishRoot = join(root, 'app', '(en)');
const MARKER = '@generated by scripts/gen-english-routes.mjs';

function walkPages(dir, acc = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) walkPages(full, acc);
    else if (entry.name === 'page.tsx') acc.push(full);
  }
  return acc;
}

function importPath(relPage) {
  const relDir = dirname(relPage);
  const depth = relDir === '.' ? 1 : relDir.split('/').length + 1;
  const target = join('[locale]', relPage).replace(/\\/g, '/').replace(/\.tsx$/, '');
  return `${'../'.repeat(depth)}${target}`;
}

function pageSource(relPage, src) {
  const spec = importPath(relPage);
  const hasMeta = /export (async )?function generateMetadata/.test(src);
  const hasStatic = /export (async )?function generateStaticParams/.test(src);
  const dynamic = relPage.includes('[');
  if (dynamic && !hasStatic) {
    throw new Error(`Dynamic route ${relPage} has no generateStaticParams`);
  }

  const lines = [
    `/* ${MARKER} */`,
    `import * as localePage from '${spec}';`,
    `import { bindEnglish } from '@/lib/english-route';`,
    '',
    'const bound = bindEnglish(localePage as never);',
    '',
  ];

  if (hasMeta) {
    lines.push(
      'export function generateMetadata(props: { params: Promise<Record<string, string | string[]>> }) {',
      '  return bound.generateMetadata(props);',
      '}',
      '',
    );
  }

  if (dynamic) {
    lines.push('export function generateStaticParams() {', '  return bound.generateStaticParams();', '}', '');
  }

  lines.push(
    'export default function Page(props: { params: Promise<Record<string, string | string[]>> }) {',
    '  return bound.Page(props);',
    '}',
    '',
  );

  return lines.join('\n');
}

const written = new Set();
for (const file of walkPages(localeRoot)) {
  const rel = relative(localeRoot, file).replace(/\\/g, '/');
  const dest = join(englishRoot, rel);
  mkdirSync(dirname(dest), { recursive: true });
  const body = pageSource(rel, readFileSync(file, 'utf8'));
  writeFileSync(dest, body);
  written.add(dest);
}

if (existsSync(englishRoot)) {
  for (const file of walkPages(englishRoot)) {
    if (written.has(file)) continue;
    const text = readFileSync(file, 'utf8');
    if (!text.includes(MARKER)) continue;
    unlinkSync(file);
  }
}

const rootPage = join(root, 'app', 'page.tsx');
if (existsSync(rootPage) && readFileSync(rootPage, 'utf8').includes("redirect('/en")) {
  rmSync(rootPage);
}

console.log(`english routes — ${written.size} pages`);
